  '',
  '$script:LancommanderManifestPath = $null',
  '',
  'function Set-LCManifestPath {',
  '    param([string]$Path)',
  '    $script:LancommanderManifestPath = $Path',
  '}',
  '',
  'function Get-SanitizedPath {',
  '    param([Parameter(ValueFromPipeline=$true)][string]$Path)',
  '    process {',
  '        if ([string]::IsNullOrEmpty($Path)) { return $Path }',
  "        return ($Path -replace '[\\\\/:*?\"<>|]', '_')",
  '    }',
  '}',
  '',
  'function Get-Runtime {',
  "    if ($IsWindows -or ($PSVersionTable.PSVersion.Major -lt 6 -and $env:OS -eq 'Windows_NT')) { return 'Windows' }",
  "    if ($IsMacOS) { return 'macOS' }",
  "    if ($IsLinux) { return 'Linux' }",
  "    return 'Windows'",
  '}',
  '',
  'function Get-GameManifest {',
  '    $manifestFile = if ($script:LancommanderManifestPath) {',
  '        $script:LancommanderManifestPath',
  '    } elseif ($GameManifest) {',
  '        $GameManifest',
  '    } else {',
  '        $null',
  '    }',
  '    if (-not $manifestFile -or -not (Test-Path $manifestFile)) { return $null }',
  '    return Get-Content -Raw -Path $manifestFile | ConvertFrom-Json',
  '}',
  '',
  'function Write-GameManifest {',
  '    param([Parameter(ValueFromPipeline=$true)]$Manifest)',
  '    process {',
  '        $manifestFile = if ($script:LancommanderManifestPath) {',
  '            $script:LancommanderManifestPath',
  '        } elseif ($GameManifest) {',
  '            $GameManifest',
  '        } else {',
  '            $null',
  '        }',
  '        if (-not $manifestFile) { return }',
  '        $Manifest | ConvertTo-Json -Depth 10 | Set-Content -Path $manifestFile -Encoding UTF8',
  '    }',
  '}',
  '',
  'function Update-IniValue {',
  '    param(',
  '        [string]$Path,',
  '        [string]$Section,',
  '        [string]$Key,',
  '        [string]$Value',
  '    )',
  '    $lines = @()',
  '    if (Test-Path $Path) { $lines = Get-Content -Path $Path }',
  '    $inSection = $false',
  '    $written = $false',
  '    $out = foreach ($line in $lines) {',
  "        if ($line -match '^\\s*\\[(.+)\\]\\s*$') {",
  '            $inSection = ($Matches[1] -eq $Section)',
  '            $line',
  '        } elseif ($inSection -and $line -match ("^\\s*" + [regex]::Escape($Key) + "\\s*=")) {',
  '            if (-not $written) { "$Key=$Value"; $written = $true }',
  '        } else {',
  '            $line',
  '        }',
  '    }',
  '    if (-not $written) { $out += "$Key=$Value" }',
  '    $out | Set-Content -Path $Path -Encoding UTF8',
  '}',
  '',
  'function Write-ReplaceContentInFile {',
  '    param(',
  '        [string]$Path,',
  '        [string]$Pattern,',
  '        [string]$Replacement',
  '    )',
  '    if (-not (Test-Path $Path)) { return }',
  '    (Get-Content -Raw -Path $Path) -replace $Pattern, $Replacement |',
  '        Set-Content -Path $Path -Encoding UTF8',
  '}',
  '',
  'function Get-GameOptions {',
  '    $manifest = Get-GameManifest',
  '    if ($manifest -and $manifest.Options) { return $manifest.Options }',
